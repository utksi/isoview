/**
 * Tests of js/analysis.js (node tests/analysis.mjs). Analytic checks:
 *   ideal gas (uniform random points, triclinic cell, rmax beyond half the cell width): g(r) = (N_a - 1) / N_a ~ 1;
 *   perfect fcc in its 1-atom primitive cell (all neighbours are periodic images): n(r) = 12, 18, 42, 54 after the shells at
 *   a / sqrt 2, a, a sqrt(3/2), a sqrt 2;
 *   constant velocity v in a cell that changes every frame, positions wrapped: MSD(t) = |v|^2 t^2, D from the slope;
 *   Gaussian random walk with step variance s^2 per component: MSD = 3 s^2 m, D = s^2 / (2 dt);
 *   harmonic oscillators x = A cos(2 pi nu0 t): VDOS peak at nu0;
 *   fixed cell: volume = |det L|, density = sum m / V.
 * Reference check: 27-atom CuAu liquid (ASE EMT Langevin MD, 2500 K, triclinic cell, 200 frames, wrapped) in
 * tests/fixtures/analysis, with g(r), n(r), MSD, D, VACF, VDOS and the temperature estimate from independent numpy
 * brute-force implementations (generated by a helper script kept outside the repo; frames saved every 2 fs MD step).
 */
import fs from "node:fs";
import { rdf, msd, vacf, perFrame, massOf, timeStepOf } from "../js/analysis.js";

let fails = 0, n = 0;
const ok = (cond, msg) => { n++; if (!cond) { fails++; console.log("FAIL", msg); } else console.log("ok  ", msg); };
const near = (a, b, tol) => Math.abs(a - b) <= tol;
const rel = (a, b) => Math.abs(a - b) / Math.max(1e-300, Math.abs(b));

/** Deterministic uniform random numbers in [0, 1) (mulberry32). */
function rng(seed) {
  return () => { seed |= 0; seed = (seed + 0x6D2B79F5) | 0; let t = Math.imul(seed ^ (seed >>> 15), 1 | seed); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}
/** Standard normal deviate by Box-Muller from a uniform generator. */
const gauss = u => Math.sqrt(-2 * Math.log(1 - u())) * Math.cos(2 * Math.PI * u());

/* ideal gas: g ~ 1 with images (triclinic cell, smallest width ~ 7.9 A, rmax 6 A) */
{
  const u = rng(1), L = [[10, 0, 0], [3, 9, 0], [2, 2, 9]], N = 300, F = 40, pos = new Float64Array(3 * N * F);
  for (let f = 0; f < F; f++) for (let i = 0; i < N; i++) {
    const s = [u(), u(), u()];
    for (let k = 0; k < 3; k++) pos[3 * (N * f + i) + k] = s[0] * L[0][k] + s[1] * L[1][k] + s[2] * L[2][k];
  }
  const species = Array.from({ length: N }, (_, i) => (i % 3 ? "Ar" : "Kr"));
  const st = { lattice: L, pbc: true, species, pos: pos.slice(0, 3 * N) };
  const R = rdf(st, { n: F, nat: N, pos, cells: null, energy: null }, { rmax: 6, dr: 0.1, frames: 1 });
  let mean = 0, cnt = 0;
  for (let k = 0; k < R.r.length; k++) if (R.r[k] > 2) { mean += R.total.g[k]; cnt++; }
  mean /= cnt;
  const g = R.pairs.find(p => p.label === "Kr-Ar").g, tail = g.slice(30).reduce((a, b) => a + b) / g.slice(30).length;
  const rho = N / 810, nExp = rho * (4 / 3) * Math.PI * 216;
  ok(near(mean, (N - 1) / N, 0.01) && near(tail, 1, 0.03), `ideal gas: <g(r>2 A)> = ${mean.toFixed(4)} (expect ${((N - 1) / N).toFixed(4)}), Kr-Ar tail ${tail.toFixed(3)}`);
  ok(rel(R.total.n[R.r.length - 1], nExp * (N - 1) / N) < 0.01, `ideal gas: n(6 A) = ${R.total.n[59].toFixed(2)} vs rho (4/3) pi r^3 = ${nExp.toFixed(2)}`);
}

/* fcc primitive cell: rmax far beyond the cell width (2.08 A), every neighbour an image */
{
  const a = 3.6, L = [[0, a / 2, a / 2], [a / 2, 0, a / 2], [a / 2, a / 2, 0]];
  const R = rdf({ lattice: L, pbc: true, species: ["Cu"], pos: new Float64Array([0.3, 0.1, 0.2]) }, null, { rmax: 5.5, dr: 0.01 });
  const at = r => R.total.n[Math.floor(r / 0.01)];
  ok(at(2.4) === 0 && at(2.6) === 12 && at(3.7) === 18 && at(4.5) === 42 && at(5.2) === 54, `fcc 1-atom cell (width 2.08 A, rmax 5.5 A): n(2.6) = ${at(2.6)}, n(3.7) = ${at(3.7)}, n(4.5) = ${at(4.5)}, n(5.2) = ${at(5.2)} (12, 18, 42, 54)`);
  const C = rdf({ lattice: [[a, 0, 0], [0, a, 0], [0, 0, a]], pbc: false, species: ["Cu", "Cu", "Cu", "Cu"], pos: new Float64Array([0, 0, 0, 0, a / 2, a / 2, a / 2, 0, a / 2, a / 2, a / 2, 0]) }, null, { rmax: 3, dr: 0.1 });
  ok(C.total.g === null && C.total.n[29] === 3 && !C.periodic, "non-periodic tetrahedron: g null, every atom has 3 neighbours");
}

/* constant velocity in a variable cell with wrapping: MSD = v^2 t^2 */
{
  const F = 60, N = 4, dt = 2, pos = new Float64Array(3 * N * F), cells = new Float64Array(9 * F);
  const v = [[0.03, -0.02, 0.01], [0.03, -0.02, 0.01], [0.03, -0.02, 0.01], [0.03, -0.02, 0.01]]; // A/fs
  for (let f = 0; f < F; f++) {
    const s = 1 + 0.05 * Math.sin(f / 5), L = [[5 * s, 0, 0], [1, 5 * s, 0], [0.5, 0.3, 5.5 * s]];
    cells.set(L.flat(), 9 * f);
    for (let i = 0; i < N; i++) {
      const r = [0.2 + 0.5 * i + v[i][0] * dt * f, 0.2 + 0.8 * i + v[i][1] * dt * f, 0.3 + v[i][2] * dt * f]; // inside the frame-0 cell
      // wrap into the cell of this frame: subtract floor(fractional) lattice vectors (upper-triangular solve)
      const c = r[2] / L[2][2], b = (r[1] - c * L[2][1]) / L[1][1], aa = (r[0] - c * L[2][0] - b * L[1][0]) / L[0][0];
      const fl = [Math.floor(aa), Math.floor(b), Math.floor(c)];
      for (let k = 0; k < 3; k++) pos[3 * (N * f + i) + k] = r[k] - fl[0] * L[0][k] - fl[1] * L[1][k] - fl[2] * L[2][k];
    }
  }
  const traj = { n: F, nat: N, pos, cells, energy: null };
  const st = { lattice: cells.slice(0, 9).reduce((A, x, k) => (A[k / 3 | 0].push(x), A), [[], [], []]), pbc: true, species: ["Na", "Na", "Cl", "Cl"], pos: pos.slice(0, 12) };
  const M = msd(st, traj, { dt_fs: dt, removeDrift: false, maxLag: 40 });
  const v2 = 0.03 ** 2 + 0.02 ** 2 + 0.01 ** 2;
  let e = 0;
  for (let m = 0; m <= 40; m++) e = Math.max(e, Math.abs(M.total.msd[m] - v2 * (m * dt) ** 2));
  ok(e < 1e-9 && M.timeUnit === "ps" && near(M.t[40], 0.08, 1e-12), `ballistic MSD = v^2 t^2 through wrapping and a changing cell (max error ${e.toExponential(1)} A^2)`);
  const D = msd(st, traj, { dt_fs: dt, removeDrift: true });
  ok(D.total.msd.every(x => x < 1e-12), "ballistic: the common drift removed leaves MSD = 0");
  const S = msd(st, traj, { removeDrift: false, stride: 3 });
  ok(S.timeUnit === "frame" && S.total.D_A2ps === null && near(S.total.msd[2], v2 * (6 * dt) ** 2, 1e-9), "no dt: lags in frames, D null; stride 3 samples every 3rd frame");
}

/* random walk: D = s^2 / (2 dt) */
{
  const u = rng(5), F = 400, N = 200, s = 0.05, dt = 1, pos = new Float64Array(3 * N * F);
  for (let i = 0; i < N; i++) {
    let x = 0, y = 0, z = 0;
    for (let f = 0; f < F; f++) {
      if (f) { x += s * gauss(u); y += s * gauss(u); z += s * gauss(u); }
      const p = 3 * (N * f + i);
      pos[p] = x; pos[p + 1] = y; pos[p + 2] = z;
    }
  }
  const M = msd({ lattice: null, pbc: false, species: Array(N).fill("Ar"), pos: pos.slice(0, 3 * N) }, { n: F, nat: N, pos, cells: null, energy: null }, { dt_fs: dt, removeDrift: false });
  const Dexp = s * s / (2 * dt) * 1000; // A^2/ps
  ok(rel(M.elements[0].D_A2ps, Dexp) < 0.05 && near(M.elements[0].D_cm2s, M.elements[0].D_A2ps * 1e-4, 1e-15), `random walk: D = ${M.elements[0].D_A2ps.toFixed(3)} A^2/ps vs s^2/(2 dt) = ${Dexp.toFixed(3)}`);
}

/* harmonic oscillators: VDOS peak at nu0 */
{
  const u = rng(9), F = 2000, N = 20, dt = 1, nu0 = 10, pos = new Float64Array(3 * N * F); // dt fs, nu0 THz
  const ph = Array.from({ length: 3 * N }, () => 2 * Math.PI * u());
  for (let f = 0; f < F; f++) for (let c = 0; c < 3 * N; c++) pos[3 * N * f + c] = c + 0.1 * Math.cos(2 * Math.PI * nu0 * 1e-3 * f * dt + ph[c]);
  const V = vacf({ lattice: null, pbc: false, species: Array(N).fill("H"), pos: pos.slice(0, 3 * N) }, { n: F, nat: N, pos, cells: null, energy: null }, { dt_fs: dt });
  let kmax = 0;
  for (let k = 1; k < V.nu_THz.length; k++) if (V.total.vdos[k] > V.total.vdos[kmax]) kmax = k;
  let area = 0;
  for (let k = 1; k < V.nu_THz.length; k++) area += 0.5 * (V.total.vdos[k] + V.total.vdos[k - 1]) * (V.nu_THz[k] - V.nu_THz[k - 1]);
  ok(near(V.nu_THz[kmax], nu0, 0.1) && near(V.nu_THz[kmax] * 33.35640952, V.nu_cm[kmax], 1e-9) && near(area, 1, 1e-12), `oscillator nu0 = 10 THz: VDOS peak at ${V.nu_THz[kmax].toFixed(3)} THz (${V.nu_cm[kmax].toFixed(1)} cm^-1), unit area`);
  ok(near(V.nyquist_THz, 500, 1e-9) && near(V.resolution_THz, 1000 / (V.t.length - 1), 1e-9) && near(V.total.z[0], 1, 1e-12) && near(V.total.z[25], Math.cos(2 * Math.PI * 0.25), 0.02), `oscillator: Nyquist 500 THz, resolution ${V.resolution_THz.toFixed(3)} THz, VACF cos(2 pi nu0 t) at a quarter period ${V.total.z[25].toFixed(3)}`);
}

/* fixture: CuAu liquid against numpy brute force */
{
  const dir = new URL("./fixtures/analysis/", import.meta.url);
  const ref = JSON.parse(fs.readFileSync(new URL("cuau27.json", dir), "utf8"));
  const raw = fs.readFileSync(new URL("cuau27.pos.f32", dir));
  const pos = Float64Array.from(new Float32Array(raw.buffer, raw.byteOffset, raw.byteLength / 4));
  const N = ref.species.length, traj = { n: ref.n, nat: N, pos, cells: null, energy: null };
  const st = { lattice: ref.cell, pbc: true, species: ref.species, pos: pos.slice(0, 3 * N) };
  const R = rdf(st, traj, { rmax: ref.rmax, dr: ref.dr, frames: 1 });
  let eg = 0;
  for (const p of R.pairs) { const r = ref.g[p.label] || ref.g[`${p.b}-${p.a}`]; for (let k = 0; k < r.length; k++) eg = Math.max(eg, Math.abs(p.g[k] - r[k])); }
  for (let k = 0; k < ref.gtot.length; k++) eg = Math.max(eg, Math.abs(R.total.g[k] - ref.gtot[k]));
  const cuau = R.pairs.find(p => p.label === "Cu-Au" || p.label === "Au-Cu"), nab = cuau.a === "Cu" ? cuau.nab : cuau.nba;
  let en = 0;
  for (let k = 0; k < ref.nCuAu.length; k++) en = Math.max(en, Math.abs(nab[k] - ref.nCuAu[k]));
  ok(eg < 1e-9 && en < 1e-12 && R.frames.length === 200, `CuAu liquid RDF (rmax 6 A > half width, triclinic) = numpy brute force over images: max |dg| ${eg.toExponential(1)}, |dn| ${en.toExponential(1)}`);
  const M = msd(st, traj, { dt_fs: ref.dt_fs });
  let em = 0, eD = 0;
  for (const e of M.elements) {
    [1, 10, 50, 100].forEach((m, j) => { em = Math.max(em, rel(e.msd[m], ref.msd[e.el][j])); });
    eD = Math.max(eD, rel(e.D_A2ps, ref.D_A2ps[e.el]));
  }
  ok(em < 1e-9 && eD < 1e-9 && M.t.length === ref.maxLag + 1, `CuAu MSD (FFT, COM removed) = numpy direct: rel ${em.toExponential(1)}; D Cu ${M.elements.find(e => e.el === "Cu").D_A2ps.toFixed(4)}, Au ${M.elements.find(e => e.el === "Au").D_A2ps.toFixed(4)} A^2/ps (rel ${eD.toExponential(1)})`);
  const V = vacf(st, traj, { dt_fs: ref.dt_fs });
  let ez = 0, ev = 0;
  for (const e of V.elements) [1, 5, 20, 60].forEach((m, j) => { ez = Math.max(ez, Math.abs(e.z[m] - ref.z[e.el][j])); });
  [1, 5, 20, 60].forEach((m, j) => { ez = Math.max(ez, Math.abs(V.total.z[m] - ref.ztot[j])); });
  [10, 40, 100, 200].forEach((k, j) => { ev = Math.max(ev, Math.abs(V.total.vdos[k] - ref.vdos[j]) / Math.max(...ref.vdos)); if (!near(V.nu_THz[k], ref.vdos_nu_THz[j], 1e-9)) ev = Infinity; });
  let kmax = 0;
  for (let k = 1; k < V.nu_THz.length; k++) if (V.total.vdos[k] > V.total.vdos[kmax]) kmax = k;
  const sum = V.elements.reduce((s, e) => s + e.vdos[kmax], 0);
  ok(ez < 1e-9 && ev < 1e-9 && near(V.nu_THz[kmax], ref.vdos_peak_THz, 1e-9) && near(sum, V.total.vdos[kmax], 1e-9), `CuAu VACF and VDOS = numpy direct cosine sums (|dz| ${ez.toExponential(1)}, |dG| ${ev.toExponential(1)}); peak ${V.nu_THz[kmax].toFixed(2)} THz; partials sum to total`);
  const P = perFrame(st, { ...traj, energy: new Float64Array(ref.n).fill(-1) }, { dt_fs: ref.dt_fs });
  let eT = 0;
  [0, 50, 150].forEach((f, j) => { eT = Math.max(eT, rel(P.temperature[f + 1], ref.T_est[j])); });
  let Tm = 0;
  for (let f = 1; f < ref.n - 1; f++) Tm += P.temperature[f] / (ref.n - 2);
  ok(eT < 1e-9 && Number.isNaN(P.temperature[0]) && Number.isNaN(P.temperature[ref.n - 1]) && rel(Tm, ref.T_ase_mean) < 0.1, `CuAu T estimate = numpy (rel ${eT.toExponential(1)}); mean ${Tm.toFixed(0)} K vs ASE kinetic ${ref.T_ase_mean.toFixed(0)} K (Langevin 2500 K)`);
  const L = ref.cell, Vc = Math.abs(L[0][0] * (L[1][1] * L[2][2] - L[1][2] * L[2][1]) - L[0][1] * (L[1][0] * L[2][2] - L[1][2] * L[2][0]) + L[0][2] * (L[1][0] * L[2][1] - L[1][1] * L[2][0]));
  const Msum = ref.species.reduce((s, e) => s + massOf(e), 0);
  ok(near(P.volume[199], Vc, 1e-9) && near(P.density[7], Msum * 1.6605390666 / Vc, 1e-12) && near(P.alpha[3], 60, 1e-9) && P.energy[5] === -1 && near(P.t[10], 0.02, 1e-15), `per-frame: V = ${Vc.toFixed(2)} A^3, density ${P.density[0].toFixed(3)} g/cm^3, alpha 60 deg, energy and time axis`);
}

ok(massOf("Cu") === 63.546 && massOf("H") === 1.008 && massOf("X") === 1 && timeStepOf({}) === null && timeStepOf({ dt_fs: 0.5 }) === 0.5, "masses (IUPAC) and timeStepOf");

console.log(`\n${n - fails}/${n} passed`);
process.exit(fails ? 1 : 0);

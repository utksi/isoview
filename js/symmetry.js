/**
 * Primitive and conventional cells of a periodic structure (lattice rows L in A, Cartesian positions).
 *
 * Pure translations: with fractional coordinates f_i wrapped into [0, 1), a vector t is a lattice translation of the
 * crystal if every atom i has an atom j of the same species with |(f_i + t - f_j - round(.)) L| < tol. Candidates are
 * t = f_j - f_0 for the atoms j of the least frequent species (atom 0 one of them); t = 0 always counts. An accepted
 * t is refined to t + <f_m(i) - f_i - t>, the mean residual over all atoms i and their matches m(i), so that noisy
 * positions still give the lattice to within the noise divided by sqrt(N).
 * Primitive basis: the successive minima of the lattice generated by L and the translations, i.e. the shortest
 * vector b1 among (t + k) L (t a translation, k in {-2..2}^3), the shortest b2 not parallel to b1 and the shortest b3
 * not in their plane; in three dimensions these always form a basis. Made right-handed and checked to generate every
 * accepted translation (within tol); the number of lattice points in the original cell is n = V / |det B|.
 * Lattice point group: integer matrices M (entries -1, 0, 1, det +-1) with M G M^T = G, G = B B^T the metric of the
 * reduced primitive basis B, within |(M G M^T - G)_ij| <= tol (|b_i| + |b_j|): the image vectors agree with the basis
 * in length to tol (A), the same tolerance as the atoms (for i = j, |b'|^2 - |b|^2 ~ 2 |b| (|b'| - |b|)). Its order fixes the
 * holohedry: 48 cubic, 24 hexagonal, 16 tetragonal, 12 rhombohedral, 8 orthorhombic, 4 monoclinic, 2 triclinic.
 * The Cartesian rotation of M is Q = B^T M^T B^-T; its proper part det(M) Q has trace 1 + 2 cos(theta), and its
 * axis is the shortest lattice vector along the rotation axis.
 * Conventional cell: cubic, the three 4-fold axes; tetragonal, c on the 4-fold axis and a, b on two perpendicular
 * 2-fold axes with the shortest a; hexagonal and rhombohedral, c on the 6- or 3-fold axis and a, b on 2-fold axes at
 * 120 degrees (the rhombohedral lattice then comes out in its triple hexagonal cell); orthorhombic, the three 2-fold
 * axes ordered by length, a base-centred cell turned so the centred face is ab (C); monoclinic, b on the 2-fold
 * axis and a, c the shortest pair in the plane perpendicular to it, beta obtuse; triclinic, the reduced primitive
 * cell. Atoms: the primitive atoms repeated by primitive translations and kept inside the new cell.
 * The result is the conventional cell of the lattice's own symmetry; for a structure whose atoms break the lattice
 * symmetry it is a valid cell of the crystal but not necessarily the standard setting of its space group.
 */
import { inv3, det3, cartToFrac, fracToCart, norm, cross, dot } from "./lattice.js?v=1002";

const wrap1 = x => { const y = x - Math.floor(x); return y >= 1 - 1e-12 ? 0 : y; };

function fracsOf(st) {
  const Li = inv3(st.lattice);
  return st.species.map((_, i) => cartToFrac(Li, [st.pos[3 * i], st.pos[3 * i + 1], st.pos[3 * i + 2]]).map(wrap1));
}

/** Hash of fractional positions per species: near(sp, g) is the index of an atom of species sp within tol (A) of g, or -1. */
function fracHash(L, F, species, tol) {
  const m = L.map(v => Math.max(1, Math.floor(norm(v) / Math.max(4 * tol, 0.6))));
  const key = (s, a, b, c) => `${s}|${a}|${b}|${c}`, bins = new Map();
  F.forEach((f, i) => {
    const k = key(species[i], ...f.map((x, a) => Math.floor(x * m[a]) % m[a]));
    if (!bins.has(k)) bins.set(k, []);
    bins.get(k).push(i);
  });
  return (sp, g) => {
    const c = g.map((x, a) => Math.floor(wrap1(x) * m[a]));
    for (let da = -1; da <= 1; da++) for (let db = -1; db <= 1; db++) for (let dc = -1; dc <= 1; dc++) {
      const list = bins.get(key(sp, ((c[0] + da) % m[0] + m[0]) % m[0], ((c[1] + db) % m[1] + m[1]) % m[1], ((c[2] + dc) % m[2] + m[2]) % m[2]));
      if (!list) continue;
      for (const j of list) {
        const d = [0, 1, 2].map(a => { const x = g[a] - F[j][a]; return x - Math.round(x); });
        if (norm(fracToCart(L, d)) < tol) return j;
      }
    }
    return -1;
  };
}

/** Fractional translations (including 0) that map the structure onto itself within tol (A), each refined to the
 *  mean over all matched atoms. */
export function translations(st, tol = 1e-5) {
  const F = fracsOf(st), sp = st.species, near = fracHash(st.lattice, F, sp, tol);
  const count = new Map();
  for (const s of sp) count.set(s, (count.get(s) || 0) + 1);
  const s0 = [...count.entries()].sort((a, b) => a[1] - b[1])[0][0];
  const ref = sp.indexOf(s0), T = [[0, 0, 0]];
  for (let j = 0; j < sp.length; j++) {
    if (j === ref || sp[j] !== s0) continue;
    const t = [0, 1, 2].map(a => wrap1(F[j][a] - F[ref][a]));
    let okT = true;
    const sum = [0, 0, 0];
    for (let i = 0; i < sp.length && okT; i++) {
      const j2 = near(sp[i], F[i].map((x, a) => x + t[a]));
      if (j2 < 0) { okT = false; break; }
      for (let a = 0; a < 3; a++) { const x = F[j2][a] - F[i][a] - t[a]; sum[a] += x - Math.round(x); }
    }
    if (okT) T.push(t.map((x, a) => wrap1(x + sum[a] / sp.length)));
  }
  return T;
}

/** Successive minima (rows, right-handed) of the lattice generated by L and the fractional translations T. */
function reducedBasis(L, T, tol) {
  const cand = [];
  for (const t of T) for (let i = -2; i <= 2; i++) for (let j = -2; j <= 2; j++) for (let k = -2; k <= 2; k++) {
    const v = fracToCart(L, [t[0] + i, t[1] + j, t[2] + k]), n = norm(v);
    if (n > 1e-6) cand.push({ v, n });
  }
  cand.sort((a, b) => a.n - b.n);
  const v1 = cand[0].v;
  const c2 = cand.find(c => norm(cross(v1, c.v)) > 1e-3 * cand[0].n * c.n);
  if (!c2) throw new Error("could not find a primitive basis");
  const v2 = c2.v, n12 = norm(cross(v1, v2));
  const c3 = cand.find(c => Math.abs(det3([v1, v2, c.v])) > 1e-3 * n12 * c.n);
  if (!c3) throw new Error("could not find a primitive basis");
  const d = det3([v1, v2, c3.v]), B = d > 0 ? [v1, v2, c3.v] : [v1, v2, c3.v.map(x => -x)];
  // every accepted translation must be a lattice vector of B
  const Bi = inv3(B);
  for (const t of T) {
    const g = cartToFrac(Bi, fracToCart(L, t)), e = fracToCart(B, g.map(x => x - Math.round(x)));
    if (norm(e) > 2 * tol) throw new Error("the translations found do not form a lattice; try a different tolerance");
  }
  return B;
}

/** Atoms of st placed in the cell with rows C: all of them wrapped into it (wrapAll), or those of the translated
 *  copies (extraT, Cartesian) that fall inside it; copies within tol of each other are merged into their mean. */
function refill(st, C, extraT, tol, wrapAll = false) {
  const Ci = inv3(C), out = [], sp = [];
  const pts = [];
  for (let i = 0; i < st.species.length; i++) for (const t of extraT) {
    const r = [0, 1, 2].map(c => st.pos[3 * i + c] + t[c]);
    const f = cartToFrac(Ci, r).map(x => (Math.abs(x - Math.round(x)) < 1e-9 ? Math.round(x) : x));
    if (!wrapAll && f.some(x => x < -1e-6 || x >= 1 - 1e-6)) continue;
    pts.push({ s: st.species[i], f: f.map(wrap1) });
  }
  for (const p of pts) {
    const q = out.find(o => o.s === p.s && norm(fracToCart(C, [0, 1, 2].map(a => { const x = p.f[a] - o.f[a]; return x - Math.round(x); }))) < tol);
    if (!q) { out.push({ ...p, d: [0, 0, 0], k: 1 }); continue; }
    for (let a = 0; a < 3; a++) { const x = p.f[a] - q.f[a]; q.d[a] += x - Math.round(x); }
    q.k++;
  }
  const pos = new Float64Array(3 * out.length);
  out.forEach((p, k) => { pos.set(fracToCart(C, p.f.map((x, a) => wrap1(x + p.d[a] / p.k))), 3 * k); sp.push(p.s); });
  return { lattice: C.map(v => v.slice()), pbc: true, species: sp, pos };
}

/** Primitive cell: { structure, n } with n the number of lattice points in the original cell (1 = already primitive). */
export function primitive(st, tol = 1e-5) {
  if (!st.pbc || !st.lattice) throw new Error("finding a primitive cell needs a periodic structure");
  const T = translations(st, tol), V = Math.abs(det3(st.lattice));
  const B = reducedBasis(st.lattice, T, tol);
  const structure = refill(st, B, [[0, 0, 0]], tol, true);
  return { structure, n: Math.round(V / Math.abs(det3(B))) };
}

/** Lattice point group of the basis B (rows, A): integer 3x3 matrices M with |(M G M^T - G)_ij| <= tol (|b_i| + |b_j|),
 *  G = B B^T, tol in A. */
export function pointGroup(B, tol = 1e-5) {
  // WHY: a fixed relative tolerance (formerly 5e-3 of |b|^2) called a 1e-3 tetragonal strain cubic at any atom tolerance
  const G = B.map(u => B.map(v => dot(u, v))), len = B.map(norm), ops = [];
  const r = [-1, 0, 1];
  for (const a of r) for (const b of r) for (const c of r) for (const d of r) for (const e of r) for (const f of r) for (const g of r) for (const h of r) for (const k of r) {
    const M = [[a, b, c], [d, e, f], [g, h, k]], D = det3(M);
    if (D !== 1 && D !== -1) continue;
    let okM = true;
    for (let i = 0; i < 3 && okM; i++) for (let j = 0; j < 3 && okM; j++) {
      let s = 0;
      for (let p = 0; p < 3; p++) for (let q = 0; q < 3; q++) s += M[i][p] * G[p][q] * M[j][q];
      if (Math.abs(s - G[i][j]) > tol * (len[i] + len[j])) okM = false;
    }
    if (okM) ops.push(M);
  }
  return ops;
}

/** Rotation axes of the proper parts of the point group: [{ order, axis (unit, Cartesian) }], one entry per axis. */
function axes(B, ops) {
  const BT = [[B[0][0], B[1][0], B[2][0]], [B[0][1], B[1][1], B[2][1]], [B[0][2], B[1][2], B[2][2]]], BTi = inv3(BT);
  const mul = (X, Y) => X.map((row, i) => [0, 1, 2].map(j => row[0] * Y[0][j] + row[1] * Y[1][j] + row[2] * Y[2][j]));
  const out = [];
  for (const M of ops) {
    const MT = [[M[0][0], M[1][0], M[2][0]], [M[0][1], M[1][1], M[2][1]], [M[0][2], M[1][2], M[2][2]]];
    let Q = mul(mul(BT, MT), BTi);
    if (det3(M) < 0) Q = Q.map(r => r.map(x => -x));
    const tr = Q[0][0] + Q[1][1] + Q[2][2], order = { "-1": 2, 0: 3, 1: 4, 2: 6 }[Math.round(tr)];
    if (!order) continue;
    let ax;
    if (order === 2) { const P = Q.map((r, i) => r.map((x, j) => (x + (i === j ? 1 : 0)) / 2)); const i = [0, 1, 2].sort((p, q) => P[q][q] - P[p][p])[0]; ax = P.map(r => r[i]); }
    else ax = [Q[2][1] - Q[1][2], Q[0][2] - Q[2][0], Q[1][0] - Q[0][1]];
    const n = norm(ax);
    if (n < 1e-8) continue;
    ax = ax.map(x => x / n);
    const e = out.find(o => Math.abs(dot(o.axis, ax)) > 0.999);
    if (e) e.order = Math.max(e.order, order); else out.push({ order, axis: ax });
  }
  return out;
}

/** Shortest lattice vector of B (rows) along the unit direction u (positive sense). */
function along(B, u) {
  let best = null, bn = Infinity;
  for (let i = -4; i <= 4; i++) for (let j = -4; j <= 4; j++) for (let k = -4; k <= 4; k++) {
    const v = fracToCart(B, [i, j, k]), n = norm(v);
    if (n < 1e-6 || dot(v, u) <= 0 || norm(cross(v, u)) > 1e-3 * n) continue;
    if (n < bn) { bn = n; best = v; }
  }
  return best;
}

const ang = (a, b) => Math.acos(Math.max(-1, Math.min(1, dot(a, b) / (norm(a) * norm(b))))) * 180 / Math.PI;
const rightHanded = C => (det3(C) < 0 ? [C[0], C[1], C[2].map(x => -x)] : C);

/**
 * True if structures a and b have the same number of atoms and the same cell up to relabelling the axes and flipping
 * a vector: equal volume (relative 1e-4), equal sorted lengths (within tol, A) and equal sorted angles taken as
 * min(theta, 180 - theta) (within 0.05 degrees). Used to tell that a cell already is the conventional one.
 */
export function sameCellShape(a, b, tol = 1e-5) {
  if (!a.lattice || !b.lattice || a.species.length !== b.species.length) return false;
  const pa = cellParams(a.lattice), pb = cellParams(b.lattice);
  const va = Math.abs(det3(a.lattice)), vb = Math.abs(det3(b.lattice));
  return Math.abs(va - vb) < 1e-4 * va && pa.len.every((x, i) => Math.abs(x - pb.len[i]) < tol) && pa.ang.every((x, i) => Math.abs(x - pb.ang[i]) < 0.05);
}
function cellParams(L) {
  const len = L.map(norm), an = [[1, 2], [0, 2], [0, 1]].map(([i, j]) => { const t = ang(L[i], L[j]); return Math.min(t, 180 - t); });
  return { len: len.sort((x, y) => x - y), ang: an.sort((x, y) => x - y) };
}

/** Conventional cell: { structure, system, z } (z = conventional / primitive volume). */
export function conventional(st, tol = 1e-5) {
  const prim = primitive(st, tol).structure;
  const B = reducedBasis(prim.lattice, [[0, 0, 0]], tol);
  const ops = pointGroup(B, tol), ax = axes(B, ops), n = ops.length;
  const of = k => ax.filter(a => a.order === k);
  const perp = (list, c) => list.filter(a => Math.abs(dot(a.axis, unit(c))) < 1e-3);
  let C, system;
  if (n === 48) { system = "cubic"; C = of(4).slice(0, 3).map(a => along(B, a.axis)); }
  else if (n === 24 || n === 12) {
    system = n === 24 ? "hexagonal" : "rhombohedral";
    const c = along(B, (n === 24 ? of(6) : of(3))[0].axis);
    const two = perp(of(2), c).map(a => along(B, a.axis)).sort((p, q) => norm(p) - norm(q));
    const a = two[0], b = two.find(v => Math.abs(ang(a, v) - 120) < 0.5 && Math.abs(norm(v) - norm(a)) < 1e-3 * norm(a))
      || two.map(v => v.map(x => -x)).find(v => Math.abs(ang(a, v) - 120) < 0.5 && Math.abs(norm(v) - norm(a)) < 1e-3 * norm(a));
    C = [a, b, c];
  } else if (n === 16) {
    system = "tetragonal";
    const c = along(B, of(4)[0].axis), two = perp(of(2), c).map(a => along(B, a.axis)).sort((p, q) => norm(p) - norm(q));
    const a = two[0], b = two.find(v => Math.abs(dot(unit(v), unit(a))) < 1e-3);
    C = [a, b, c];
  } else if (n === 8) {
    system = "orthorhombic";
    C = of(2).map(a => along(B, a.axis)).sort((p, q) => norm(p) - norm(q));
  } else if (n === 4) {
    system = "monoclinic";
    const b = along(B, of(2)[0].axis), bu = unit(b), inPlane = [];
    for (let i = -3; i <= 3; i++) for (let j = -3; j <= 3; j++) for (let k = -3; k <= 3; k++) {
      const v = fracToCart(B, [i, j, k]);
      if (norm(v) > 1e-6 && Math.abs(dot(v, bu)) < 1e-4 * norm(v)) inPlane.push(v);
    }
    inPlane.sort((p, q) => norm(p) - norm(q));
    const a = inPlane[0];
    let c = inPlane.find(v => norm(cross(a, v)) > 1e-4 * norm(a) * norm(v));
    if (dot(a, c) > 0) c = c.map(x => -x);
    C = [a, b, c];
    if (det3(C) < 0) C = [a, b.map(x => -x), c];
  } else { system = "triclinic"; C = B; }
  if (!C || C.some(v => !v)) throw new Error(`could not build the ${system} conventional cell`);
  C = rightHanded(C);
  const z = Math.round(Math.abs(det3(C)) / Math.abs(det3(prim.lattice)));
  // primitive translations that can reach the new cell
  const K = C.map(v => cartToFrac(inv3(prim.lattice), v)), m = Math.ceil(Math.max(...K.flat().map(Math.abs))) * 2 + 1;
  const T = [];
  for (let i = -m; i <= m; i++) for (let j = -m; j <= m; j++) for (let k = -m; k <= m; k++) T.push(fracToCart(prim.lattice, [i, j, k]));
  let structure = refill(prim, C, T, tol);
  if (system === "orthorhombic") structure = cFace(structure, prim, tol);
  return { structure, system, z };
}
const unit = v => { const n = norm(v); return v.map(x => x / n); };

/** Orthorhombic: if the centred face is bc (A) or ac (B), relabel the axes cyclically so it is ab (C). */
function cFace(st, prim, tol) {
  const L = st.lattice, Pi = inv3(prim.lattice);
  const isLattice = f => { const k = cartToFrac(Pi, fracToCart(L, f)); return k.every(x => Math.abs(x - Math.round(x)) < 1e-4); };
  let perm = null;
  if (isLattice([0, 0.5, 0.5]) && !isLattice([0.5, 0.5, 0])) perm = [1, 2, 0];
  else if (isLattice([0.5, 0, 0.5]) && !isLattice([0.5, 0.5, 0])) perm = [2, 0, 1];
  if (!perm) return st;
  return { ...st, lattice: perm.map(i => L[i].slice()) };
}
